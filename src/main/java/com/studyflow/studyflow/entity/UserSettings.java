package com.studyflow.studyflow.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.OneToOne;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Per-user study preferences. Maps to the "user_settings" table.
 *
 * Each {@link User} has at most ONE settings record — the unique
 * {@code user_id} join column enforces this. The record is optional: a user
 * with no row falls back to the documented defaults, so every feature works
 * out-of-the-box before the user ever opens the Settings page. A row is
 * created lazily the first time the user's settings are written (or when the
 * Settings page is opened), never eagerly at registration.
 *
 * Only approved preference values live here. Identity (email), credentials
 * (password hash) and role stay on {@link User}, and notification categories
 * live on {@link NotificationPreference} — this table never duplicates them.
 */
@Entity
@Table(name = "user_settings")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
public class UserSettings {

    /** Default focus-session duration in minutes. */
    public static final int DEFAULT_FOCUS_DURATION_MINUTES = 25;

    /** Default session type for new study sessions and the Focus Timer. */
    public static final StudySessionType DEFAULT_SESSION_TYPE = StudySessionType.FOCUS;

    /** Default weekly study goal in minutes (5 hours). */
    public static final int DEFAULT_WEEKLY_STUDY_GOAL_MINUTES = 300;

    /**
     * Primary key, generated by MySQL.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * The owning user. The unique join column guarantees a single settings
     * record per user.
     */
    @OneToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false, unique = true)
    private User user;

    /**
     * Initial duration in minutes used when the Focus Timer opens.
     * Defaults to 25 minutes.
     */
    @Column(name = "default_focus_duration_minutes", nullable = false)
    private int defaultFocusDurationMinutes = DEFAULT_FOCUS_DURATION_MINUTES;

    /**
     * Session type preselected when starting a new study session or the
     * Focus Timer. Defaults to FOCUS. Stored as a STRING so the enum values
     * survive renames/insertions.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "default_session_type", nullable = false)
    private StudySessionType defaultSessionType = DEFAULT_SESSION_TYPE;

    /**
     * The user's weekly study goal in minutes. The dashboard and (future)
     * analytics share this single value; the goal is never duplicated
     * anywhere else. Defaults to 300 minutes (5 hours).
     */
    @Column(name = "weekly_study_goal_minutes", nullable = false)
    private int weeklyStudyGoalMinutes = DEFAULT_WEEKLY_STUDY_GOAL_MINUTES;
}