package com.studyflow.studyflow.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.OneToOne;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Per-user notification category preferences. Maps to the
 * "notification_preferences" table.
 *
 * Each {@link User} has at most ONE preference record — the unique
 * {@code user_id} join column enforces this. The record is optional: a user
 * with no row is treated as having every category enabled, so notifications
 * work out-of-the-box without requiring the user to create settings first.
 *
 * All categories default to {@code enabled} for new users. Disabling a
 * category only stops FUTURE generation of that type — it never deletes
 * existing notification history.
 */
@Entity
@Table(name = "notification_preferences")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
public class NotificationPreference {

    /**
     * Primary key, generated by MySQL.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * The owning user. The unique join column guarantees a single preference
     * row per user.
     */
    @OneToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false, unique = true)
    private User user;

    /**
     * Whether Task Due notifications are generated. Defaults to enabled.
     */
    @Column(name = "task_due_enabled", nullable = false)
    private boolean taskDueEnabled = true;

    /**
     * Whether Task Overdue notifications are generated. Defaults to enabled.
     */
    @Column(name = "task_overdue_enabled", nullable = false)
    private boolean taskOverdueEnabled = true;

    /**
     * Whether Exam Upcoming notifications are generated. Defaults to enabled.
     */
    @Column(name = "exam_upcoming_enabled", nullable = false)
    private boolean examUpcomingEnabled = true;

    /**
     * Whether Exam Today notifications are generated. Defaults to enabled.
     */
    @Column(name = "exam_today_enabled", nullable = false)
    private boolean examTodayEnabled = true;

    /**
     * Whether Study Reminder notifications are generated. Defaults to enabled.
     */
    @Column(name = "study_reminder_enabled", nullable = false)
    private boolean studyReminderEnabled = true;

    /**
     * Whether Streak Reminder notifications are generated. Defaults to enabled.
     */
    @Column(name = "streak_reminder_enabled", nullable = false)
    private boolean streakReminderEnabled = true;

    /**
     * Whether System notifications are generated. Defaults to enabled.
     */
    @Column(name = "system_enabled", nullable = false)
    private boolean systemEnabled = true;

    /**
     * Whether the given notification category is enabled for this user.
     *
     * Pure lookup (no DB access). A null/missing category falls back to
     * enabled so no value silently blocks a notification.
     *
     * @param type the notification category
     * @return true when the category may be generated
     */
    public boolean isEnabled(NotificationType type) {
        if (type == null) {
            return true;
        }
        switch (type) {
            case TASK_DUE:
                return taskDueEnabled;
            case TASK_OVERDUE:
                return taskOverdueEnabled;
            case EXAM_UPCOMING:
                return examUpcomingEnabled;
            case EXAM_TODAY:
                return examTodayEnabled;
            case STUDY_REMINDER:
                return studyReminderEnabled;
            case STREAK_REMINDER:
                return streakReminderEnabled;
            case SYSTEM:
                return systemEnabled;
            default:
                return true;
        }
    }
}
